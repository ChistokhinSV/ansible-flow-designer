// Generated-file bookkeeping: recognise our files and tell hand edits apart (ADR-0009).
import { CHECKSUM_PREFIX } from './optionA';
import { checksum } from './util';

export const GENERATED_MARK = '# GENERATED by Ansible Flow Designer';

export interface GeneratedState {
  /** Starts with our header. */
  ours: boolean;
  /** Ours, but the body no longer matches the recorded checksum. */
  edited: boolean;
}

export function generatedState(text: string): GeneratedState {
  if (!text.startsWith(GENERATED_MARK)) return { ours: false, edited: false };
  const at = text.indexOf(`\n${CHECKSUM_PREFIX}`);
  if (at < 0) return { ours: true, edited: true };
  const lineEnd = text.indexOf('\n', at + 1);
  const recorded = text.slice(at + 1 + CHECKSUM_PREFIX.length, lineEnd < 0 ? undefined : lineEnd);
  const body = lineEnd < 0 ? '' : text.slice(lineEnd + 1).replaceAll('\r\n', '\n');
  return { ours: true, edited: checksum(body) !== recorded.trim() };
}
