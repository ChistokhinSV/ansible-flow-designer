// Option A code generation (AFD-4 acceptance 1 and 2). Runs in real Ansible: test/engine.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { parse } from 'yaml';
import { generatedState } from '../../../src/core/engine/files';
import { optionA } from '../../../src/core/engine/optionA';
import { durationSeconds } from '../../../src/core/engine/util';
import type { FlowDocument } from '../../../src/core/flow/types';
import { validateFlow } from '../../../src/core/flow/validate';
import { EXAMPLES_DIR, readExample } from './helpers';

const docOf = (text: string) => parse(text) as FlowDocument;
const generate = (name: string, simulate = false) =>
  optionA.generate(docOf(readExample(name)), { source: name, simulate });

describe('golden files', () => {
  it.each([
    ['edge-baseline.flow.yaml', ['edge-baseline.yml']],
    [
      'os-upgrade.flow.yaml',
      [
        'os-upgrade-edge.yml',
        'os-upgrade-edge.upgrade-os.yml',
        // AWX workflow segments at the change approval (AFD-11).
        'os-upgrade-edge.seg_start.yml',
        'os-upgrade-edge.seg_change-approval-approved.yml',
        'os-upgrade-edge.seg_change-approval-rejected.yml',
        'os-upgrade-edge.seg_finish.yml',
      ],
    ],
  ])('%s generates examples/generated byte for byte', (flow, files) => {
    const result = generate(flow);
    expect(result.ok).toBe(true);
    expect(result.files.map((f) => f.name)).toEqual(files);
    for (const f of result.files)
      expect(f.text).toBe(readFileSync(join(EXAMPLES_DIR, 'generated', f.name), 'utf8'));
  });

  it('is deterministic and keeps the flow line endings', () => {
    const text = readExample('os-upgrade.flow.yaml');
    const a = optionA.generate(docOf(text), { source: 'x.flow.yaml' });
    const b = optionA.generate(docOf(text), { source: 'x.flow.yaml' });
    expect(a.files).toEqual(b.files);
    const crlf = optionA.generate(docOf(text), { source: 'x.flow.yaml', eol: '\r\n' });
    expect(crlf.files[0]?.text).toBe(a.files[0]?.text.replaceAll('\n', '\r\n'));
  });
});

describe('plays', () => {
  it.each(['edge-baseline.flow.yaml', 'os-upgrade.flow.yaml'])(
    '%s: every connected node of every level has exactly one tagged play',
    (flow) => {
      const doc = docOf(readExample(flow));
      const result = generate(flow);
      // Level files only: AWX segment files repeat their plays (AFD-11).
      const plays = result.files
        .filter((f) => !f.name.includes('.seg_'))
        .flatMap((f) => parse(f.text) as Record<string, unknown>[]);
      const levels = [doc.nodes, ...doc.nodes.map((n) => n.subflow?.nodes ?? [])];
      for (const node of levels.flat()) {
        if (node.type === 'start' || node.type === 'end') continue;
        const mine = plays.filter((p) =>
          (p.tags as string[] | undefined)?.includes(`node_${node.id}`),
        );
        // A node with an inventory_target (AFD-14) has three: arriving hosts, the work, route.
        const override = !!node.settings?.inventory_target && !node.subflow?.nodes?.length;
        expect(mine, node.key).toHaveLength(override ? 3 : 1);
        if (override)
          expect(mine.map((p) => p.name)).toEqual([
            `[${node.key}] ${node.title}: arriving hosts`,
            `[${node.key}] ${node.title}`,
            `[${node.key}] ${node.title}: route`,
          ]);
        for (const p of mine)
          if (!p.import_playbook)
            expect((p.vars as Record<string, string>).flow_node_id).toBe(node.id);
        const play = mine[0] as Record<string, unknown>;
        if (node.subflow?.nodes?.length) {
          expect(play.import_playbook).toBe(`${doc.flow.key}.${node.key}.yml`);
          continue;
        }
        expect(String(play.name).startsWith(`[${node.key}] `)).toBe(true);
        expect((play.vars as Record<string, string>).flow_node_id).toBe(node.id);
        const range = result.plays[node.id];
        const file = result.files.find((f) => f.name === range?.file);
        expect(file?.text.split('\n')[range?.start ?? -1]).toBe(`- name: "${play.name}"`);
      }
    },
  );

  it('the start pattern comes from the targets input and plays follow the graph order', () => {
    const plays = parse(generate('edge-baseline.flow.yaml').files[0]?.text ?? '') as {
      name: string;
      hosts: string;
    }[];
    expect(plays.map((p) => p.name)).toEqual([
      '[precheck] Pre-checks',
      '[backup-config] Backup config',
      '[push-baseline] Push baseline',
      '[validate] Validate',
      '[rollback] Rollback',
      '[edge-baseline] Outcome',
    ]);
    expect(plays[0]?.hosts).toBe("{{ devices | join(',') }}");
    expect(plays[4]?.hosts).toBe('flow_push_baseline_failed_hosts');
  });

  it('every task node rescues; open and decided ports fail in the outcome play with the reason', () => {
    const text = generate('edge-baseline.flow.yaml').files[0]?.text ?? '';
    expect(text.match(/ {6}rescue:/g)).toHaveLength(5);
    expect(text).toContain(
      '# failed_hosts is open on purpose: these hosts stop in the outcome play',
    );
    expect(text).toContain(
      'Stopped at [backup-config] Backup config: failed_hosts open on purpose (Fails before any change; stopping is safe)',
    );
    expect(text).toContain('Ended at [failed] Failed (outcome: failed)');
  });

  it('module bindings route unreachable and unchanged; inner ports bubble to the subflow', () => {
    const inner = generate('os-upgrade.flow.yaml').files[1]?.text ?? '';
    expect(inner).toContain(
      "key: \"{{ 'flow_upgrade_os_unreachable' if (wait_for_ssh_result.unreachable | default(false)) else 'flow_upgrade_os__wait_for_ssh_ok_hosts' }}\"",
    );
    expect(inner).toContain('ignore_unreachable: true');
    expect(inner).toContain('# failed_hosts leaves this level as [upgrade-os] failed_hosts');
    expect(inner).toContain('tasks_from: stage');
    expect(inner).toContain('serial: 25%');
    expect(inner).not.toContain('flow_upgrade_os__set_boot_variable_unreachable');
  });

  it('simulation hooks appear only in simulate builds', () => {
    expect(generate('edge-baseline.flow.yaml').files[0]?.text).not.toContain('afd_sim');
    expect(generate('edge-baseline.flow.yaml', true).files[0]?.text).toContain(
      'afd_sim: "{{ (afd_simulate | default({}))[\'precheck\'] | default({}) }}"',
    );
  });
});

describe('refusals and findings', () => {
  it('needs a host_list input to target', () => {
    const doc = docOf(readExample('edge-baseline.flow.yaml'));
    doc.flow.inputs = { site: { type: 'string' } };
    const result = optionA.generate(doc, { source: 'x' });
    expect(result.ok).toBe(false);
    expect(result.findings.map((f) => f.code)).toEqual(['codegen-no-targets']);
  });

  it('refuses a level with a cycle', () => {
    const doc = docOf(readExample('edge-baseline.flow.yaml'));
    const [a, b] = [doc.nodes[1], doc.nodes[2]];
    doc.edges.push({
      id: '01JBZZZZZZZZZZZZZZZZZZZZZZ',
      from: { node: b?.id ?? '', port: 'failed_hosts' },
      to: { node: a?.id ?? '', port: 'in' },
    });
    const result = optionA.generate(doc, { source: 'x' });
    expect(result.ok).toBe(false);
    expect(result.findings[0]?.code).toBe('codegen-cycle');
  });

  it('playbook bindings import the playbook for the arriving hosts, then route ok_hosts', () => {
    const doc = docOf(readExample('edge-baseline.flow.yaml'));
    const node = doc.nodes.find((n) => n.key === 'validate');
    if (node) node.impl = { kind: 'playbook', ref: 'playbooks/validate.yml' };
    const result = optionA.generate(doc, { source: 'x', root: '../..' });
    expect(result.ok).toBe(true);
    const plays = parse(result.files[0]?.text ?? '') as Record<string, unknown>[];
    const at = plays.findIndex((p) => p.import_playbook === '../../playbooks/validate.yml');
    expect(at).toBeGreaterThan(0);
    expect((plays[at]?.vars as Record<string, string> | undefined)?.afd_hosts).toBe(
      plays[at + 1]?.hosts,
    );
    expect(JSON.stringify(plays[at + 1]?.tasks)).toContain('flow_validate_ok_hosts');
  });
});

describe('data passing (M5)', () => {
  const flowWith = (setup: (doc: FlowDocument) => void) => {
    const doc = docOf(readExample('edge-baseline.flow.yaml'));
    setup(doc);
    return parse(optionA.generate(doc, { source: 'x' }).files[0]?.text ?? '') as {
      name: string;
      vars?: Record<string, unknown>;
      tasks?: { block?: Record<string, unknown>[] }[];
    }[];
  };
  const play = (plays: ReturnType<typeof flowWith>, key: string) =>
    plays.find((p) => p.name.startsWith(`[${key}]`));

  it('passes upstream outputs in as play vars and skips same-name references', () => {
    const plays = flowWith((doc) => {
      const validate = doc.nodes.find((n) => n.key === 'validate');
      if (validate)
        validate.inputs = {
          baseline: { type: 'string', from: 'backup-config.backup_ref' },
          backup_ref: { type: 'string', from: 'backup-config.backup_ref' },
        };
    });
    expect(play(plays, 'validate')?.vars).toMatchObject({ baseline: '{{ backup_ref }}' });
    expect(play(plays, 'validate')?.vars).not.toHaveProperty('backup_ref');
  });

  it('reads a module output from its registered result', () => {
    const plays = flowWith((doc) => {
      const backup = doc.nodes.find((n) => n.key === 'backup-config');
      const validate = doc.nodes.find((n) => n.key === 'validate');
      if (!backup || !validate) return;
      backup.impl = { kind: 'module', ref: 'cisco.ios.ios_config', register: 'backup_out' };
      backup.outputs = { backup_ref: { type: 'string', from: 'impl.register.backup_path' } };
      validate.inputs = { baseline: { type: 'string', from: 'backup-config.backup_ref' } };
    });
    expect(play(plays, 'validate')?.vars).toMatchObject({
      baseline: '{{ backup_out.backup_path }}',
    });
  });

  it('unbound nodes set placeholder facts for their outputs', () => {
    const block =
      play(
        flowWith(() => {}),
        'backup-config',
      )?.tasks?.[0]?.block ?? [];
    expect(block.map((t) => Object.keys(t).find((k) => k.startsWith('ansible.')))).toContain(
      'ansible.builtin.set_fact',
    );
  });
});

describe('generated files', () => {
  it('detects hand edits through the checksum', () => {
    const text = generate('edge-baseline.flow.yaml').files[0]?.text ?? '';
    expect(generatedState(text)).toEqual({ ours: true, edited: false });
    expect(generatedState(text.replaceAll('\n', '\r\n'))).toEqual({ ours: true, edited: false });
    expect(generatedState(text.replace('TODO: Save', 'Save'))).toEqual({
      ours: true,
      edited: true,
    });
    expect(generatedState('- hosts: all\n')).toEqual({ ours: false, edited: false });
  });

  it('parses durations', () => {
    expect([durationSeconds('15m'), durationSeconds('4h'), durationSeconds('1h30m')]).toEqual([
      900, 14400, 5400,
    ]);
    expect([durationSeconds('90'), durationSeconds('soon'), durationSeconds(undefined)]).toEqual([
      90,
      undefined,
      undefined,
    ]);
  });
});

describe('validator: what the engine cannot drive', () => {
  const codes = (doc: FlowDocument) => validateFlow(doc).findings.map((f) => f.code);

  it('warns about unreachable/unchanged on role nodes and timeout without a setting', () => {
    const doc = docOf(readExample('edge-baseline.flow.yaml'));
    const push = doc.nodes.find((n) => n.key === 'push-baseline');
    if (push) push.ports = ['unreachable', 'unchanged', 'timeout'];
    const found = validateFlow(doc).findings.filter(
      (f) =>
        f.node === push?.id && (f.code.startsWith('port-role') || f.code.startsWith('timeout')),
    );
    expect(found.map((f) => `${f.code}:${f.port}`).sort()).toEqual([
      'port-role-unroutable:unchanged',
      'port-role-unroutable:unreachable',
      'timeout-without-setting:timeout',
    ]);
    expect(codes(docOf(readExample('os-upgrade.flow.yaml')))).not.toContain('port-role-unroutable');
  });

  it('warns when no host_list input seeds start', () => {
    const doc = docOf(readExample('edge-baseline.flow.yaml'));
    expect(codes(doc)).not.toContain('no-targets');
    doc.flow.inputs = {};
    expect(codes(doc)).toContain('no-targets');
  });
});
